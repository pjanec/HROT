def guid(block, n):
    return f"d5e1{block:04x}-0000-4000-8000-{n:012d}"


def man(name, x, y, yaw_quat=(0, 0, 0, 1), side="Friend"):
    return {
        "SimTransform": {"Position": [x, y, 0], "Rotation": list(yaw_quat)},
        "Health": {"Current": 100, "Max": 100},
        "TkbIdentity": {"TkbType": SOLDIER},
        "EntityInfo": {"Name": name, "ForceId": side},
        "TargetMemory": {"Entries": []},
        "Sop": {"Name": "InertSop", "Params": {}, "Origin": "Superior"},
    }


def device(name, tkb, host, seat, x=0, y=0):
    return {
        "SimTransform": {"Position": [x, y, 0], "Rotation": [0, 0, 0, 1]},
        "TkbIdentity": {"TkbType": tkb},
        "EntityInfo": {"Name": name, "ForceId": "Friend"},
        "IsEmbarkedTag": {"Vehicle": host, "Seat": seat},
    }


def observer_with(block, kit, at=(0, 0)):
    """The observer at `at` facing +x, his kit stations holding `kit` = [(name, tkb, seat)]."""
    ents = {}
    obs = guid(block, 1)
    o = man("Observer", at[0], at[1])
    o["PassengerBuffer"] = {"Count": len(kit), "Passengers": [guid(block, 10 + i) for i in range(len(kit))], "Seats": [s for (_, _, s) in kit]}
    ents[obs] = o
    for i, (name, tkb, seat) in enumerate(kit):
        ents[guid(block, 10 + i)] = device(name, tkb, obs, seat, at[0], at[1])
    return ents


def scenario(name, what, judge, entities):
    return {
        "$meta": {"docType": "Hrot.Scenario", "schemaVersion": 1},
        "header": {
            "subsystemType": "Hrot.Scenario", "schemaVersion": "1.0", "terrainName": "berlin",
            "description": f"What: {what} Judge: {judge} Check: scripts/scenario-regression.sh {name}",
        },
        "entities": entities,
    }


def mem(name, who, typ, field, op, value, **extra):
    row = {"name": name, "on": "field", "who": who, "memory": typ, "field": field, "op": op, "value": value}
    row.update(extra)
    return row


def write(name, scen, checks, slice_id="SD-S1"):
    d = os.path.join(ROOT, name)
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "scenario.json"), "w", encoding="utf-8") as f:
        json.dump(scen, f, indent=2, ensure_ascii=False)
        f.write("\n")
    checks = {"$doc": f"docs/designs/devices/DESIGN_Simulated_Devices.md §5a — {name} ({slice_id}). Generated by scripts/gen-devices-scenarios.py.", **checks}
    with open(os.path.join(d, "checks.json"), "w", encoding="utf-8") as f:
        json.dump(checks, f, indent=2, ensure_ascii=False)
        f.write("\n")


