#!/usr/bin/env python3
"""terrain-from-sumo.py — build an HROT terrain folder from a SUMO net and its building data.

  scripts/terrain-from-sumo.py --net NET.xml --buildings buildings.json --name demo-city \
      --box MINX MINY MAXX MAXY [--out DIR] [--lat 52.52 --lon 13.405]

The terrain is the box (in the net's own coordinates); everything outside it is background traffic over the ambient
ground (AQ93 R-4040, V8). The net is copied UNCHANGED (D1) and placed by an ANCHOR (E1b): terrain local = net − anchor,
anchor = the box's lower-left corner, so the terrain's own coordinates start at (0, 0). Only data buildings that lie
wholly inside the box are kept — as solid prisms with their heights; no procedural buildings (R-4052).

📄 docs/blueprints/Architect_Question_93_Sumo_Traffic_Node.md §11.3 (D1–D5, R-4052). Pure stdlib, deterministic.
"""
import argparse
import json
import os
import shutil


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--net", required=True)
    ap.add_argument("--buildings", required=True)
    ap.add_argument("--name", required=True)
    ap.add_argument("--box", type=float, nargs=4, required=True, metavar=("MINX", "MINY", "MAXX", "MAXY"))
    ap.add_argument("--out", default=None, help="default: assets/terrain/<name>")
    ap.add_argument("--lat", type=float, default=52.52)
    ap.add_argument("--lon", type=float, default=13.405)
    ap.add_argument("--source", default="", help="provenance text recorded in the world file description")
    ap.add_argument("--houses", default=None, help="CE-4028: an AUTHORED placements file ({features: [...]}) of template buildings with doors, "
                    "appended as they are (templates in the terrain folder's buildings/); default: <out>/<name>.houses.json when present")
    a = ap.parse_args()

    root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    out = a.out or os.path.join(root, "assets", "terrain", a.name)
    os.makedirs(out, exist_ok=True)
    minx, miny, maxx, maxy = a.box
    ax, ay = minx, miny

    net_file = f"{a.name}.net.xml"
    shutil.copyfile(a.net, os.path.join(out, net_file))

    with open(a.buildings, encoding="utf-8") as f:
        buildings = json.load(f)["buildings"]

    def inside(pt) -> bool:
        return minx <= pt[0] <= maxx and miny <= pt[1] <= maxy

    features = []
    for b in buildings:
        fp = b["footprint"]
        if not all(inside(p) for p in fp):
            continue
        ring = [[round(p[0] - ax, 3), round(p[1] - ay, 3)] for p in fp]
        if ring[0] != ring[-1]:
            ring.append(list(ring[0]))
        features.append({
            "type": "Feature",
            "properties": {"kind": "building", "height": float(b.get("height_m", 10.0)),
                           "floors": int(b.get("levels", 1)), "label": b.get("id", "")},
            "geometry": {"type": "Polygon", "coordinates": [ring]},
        })

    # ⭐ CE-4028 — enterable houses: AUTHORED template placements (doors a frightened civilian can run in through), never generated
    #   here (R-4052: no procedural buildings); the templates live in the terrain folder's buildings/.
    houses_file = a.houses or os.path.join(out, f"{a.name}.houses.json")
    houses = json.load(open(houses_file, encoding="utf-8"))["features"] if os.path.exists(houses_file) else []
    data_buildings = len(features)
    features += houses

    width, height = maxx - minx, maxy - miny
    world = {
        "type": "FeatureCollection",
        "hrot": {
            "schemaVersion": 1,
            "bounds": [0, 0, width, height],
            "groundZ": 0,
            "description": (f"Generated by scripts/terrain-from-sumo.py from {a.source or os.path.basename(a.net)}: "
                            f"the box [{minx:g},{miny:g}]-[{maxx:g},{maxy:g}] of the SUMO net, flat, with the data buildings "
                            f"wholly inside it ({data_buildings}), plus {len(houses)} authored enterable houses ({os.path.basename(houses_file)}, CE-4028). Local metres = net metres minus the anchor "
                            f"({ax:g}, {ay:g}); X east, Y north, Z up. AQ93 §11.3."),
        },
        "features": features,
    }
    world_file = f"{a.name}.world.geojson"
    with open(os.path.join(out, world_file), "w", encoding="utf-8") as f:
        json.dump(world, f, indent=2)
        f.write("\n")

    terrain = {
        "$comment": "Generated by scripts/terrain-from-sumo.py — AQ93 §11.3 (R-4052): the SUMO net is a terrain asset (R-4021), "
                    "placed by an anchor because it is not georeferenced (E1b).",
        "schemaVersion": 2,
        "origin": {"lat": a.lat, "lon": a.lon, "alt": 0.0},
        "name": a.name,
        "world": world_file,
        "sumoNet": {"file": net_file, "anchor": [ax, ay]},
    }
    with open(os.path.join(out, "terrain.json"), "w", encoding="utf-8") as f:
        json.dump(terrain, f, indent=2)
        f.write("\n")

    print(f"{a.name}: {data_buildings} data buildings + {len(houses)} houses, bounds {width:g} x {height:g} m, net {net_file}, anchor ({ax:g}, {ay:g}) -> {out}")


if __name__ == "__main__":
    main()
