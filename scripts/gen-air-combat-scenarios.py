def attack(target_gid):
    return {"Name": "AirPlatformAttack", "Params": {"Target": target_gid}, "Origin": "Superior"}


def pilot(skill, lapse=None):
    st = {"Skill": skill}
    if lapse: st["ForcedLapse"] = lapse
    return st


def shot(by, n=1, **kw):
    r = {"on": "shot", "by": by, "n": n}
    r.update(kw)
    return r


ALT = 2000   # the fights fly 2 km over the hills (never near the GCAS floor)


def fighter(name, tkb, pos, heading_deg, speed, force, target_gid, skill="Veteran", lapse=None, **extra):
    h = math.radians(heading_deg)
    vel = (speed * math.cos(h), speed * math.sin(h), 0)
    z = ground_beyond(pos[0], pos[1]) + ALT if len(pos) == 2 else pos[2]
    return jet(name, tkb, (pos[0], pos[1], z), yaw(heading_deg), vel, force=force, Behavior=attack(target_gid),
               AirCombatState=pilot(skill, lapse), **extra)


