#!/usr/bin/env python3
"""CE-10001 (air lane) — writes the `air-range` terrain and the air-combat feature-test scenarios (docs/designs/air-attack/DESIGN_Air_Combat.md §6).

The terrain is generated (not drawn): 2 x 2 km at 100 m cells — rolling hills, a 200 m ridge along x 500 (south of y 400) and a wall rising
1:1.8 to a 720 m plateau (north of y 600); beyond its edge the engine continues the edge height + low hills, so the ridge and the plateau run on.
⚠ 2 km, not more: an 8 or 24 km grid did not load in the regression's 30 s (the first load bakes its navmesh — measured). Every number a check states is computed here from the SAME height function, so the checks cannot
drift from the ground they judge.   Run:  python3 scripts/gen-air-combat-scenarios.py
"""
import json, math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CELL, HALF = 100.0, 1000.0
N = int(2 * HALF / CELL) + 1


def ground(x, y):
    """The grid covers only 2 x 2 km (the first load bakes a navmesh over it — 24 km did not load in 30 s); BEYOND its edge the engine
    continues the edge height + low hills (S0 ②), so the ridge runs on north-south and the plateau north for ever."""
    h = 100.0 + 40.0 * math.sin(x / 300.0) * math.cos(y / 350.0)
    if y < 400.0:
        h += 200.0 * math.exp(-((x - 500.0) / 150.0) ** 2)
    if y > 600.0:
        h += min(720.0, (y - 600.0) * 1.8)
    return h


def hills(x, y):
    """BeyondGround.Hills, ported exactly (FDP/Toolkits/Fdp.Toolkits/Terrain/BeyondGround.cs)."""
    tau, w = 2 * math.pi, 0.65
    h = 2.5 * math.sin(tau * (0.8 * x + 0.6 * y) / (900 * w) + 0.7) + 2.5 * math.sin(tau * (-0.6 * x + 0.8 * y) / (760 * w) + 2.1)
    h += 1.5 * math.sin(tau * (0.28 * x + 0.96 * y) / (480 * w) + 4.0) + 1.5 * math.sin(tau * (0.96 * x - 0.28 * y) / (410 * w) + 1.3)
    h += 1.0 * math.sin(tau * (0.6 * x - 0.8 * y) / (260 * w) + 5.2) + 1.0 * math.sin(tau * (0.8 * x + 0.6 * y) / (290 * w) + 3.3)
    return h * 2.5


def ground_beyond(x, y):
    """What the engine answers anywhere (TerrainWorld.GroundHeightOf): inside the grid its sample; outside, the nearest edge point's height +
    the hills faded in over 300 m (BeyondGround.HeightAt, Ramp)."""
    cx, cy = min(max(x, -HALF), HALF), min(max(y, -HALF), HALF)
    edge = grid(cx, cy)
    d = math.hypot(x - cx, y - cy)
    if d == 0:
        return edge
    t = min(max(d / 300.0, 0.0), 1.0)
    return edge + hills(x, y) * t * t * (3 - 2 * t)


def grid(x, y):
    """The ground as the engine samples it: bilinear on the 200 m grid (TerrainHeightGrid.Sample)."""
    fx = min(max((x + HALF) / CELL, 0.0), N - 1.0)
    fy = min(max((y + HALF) / CELL, 0.0), N - 1.0)
    c0, r0 = min(int(fx), N - 2), min(int(fy), N - 2)
    u, v = fx - c0, fy - r0
    z = lambda c, r: round(ground(-HALF + c * CELL, -HALF + r * CELL), 1)
    z00, z10, z01, z11 = z(c0, r0), z(c0 + 1, r0), z(c0, r0 + 1), z(c0 + 1, r0 + 1)
    # the engine's two triangles (TerrainHeightGrid.Sample), on the grid's ROUNDED posts (the .asc holds 0.1 m)
    return z00 + u * (z10 - z00) + v * (z11 - z10) if u >= v else z00 + v * (z01 - z00) + u * (z11 - z01)


def write_terrain():
    d = os.path.join(ROOT, "assets", "terrain", "air-range")
    os.makedirs(d, exist_ok=True)
    rows = []
    for r in range(N - 1, -1, -1):   # ESRI ASCII: the first row is the NORTH edge
        y = -HALF + r * CELL
        rows.append(" ".join(f"{ground(-HALF + c * CELL, y):.1f}" for c in range(N)))
    with open(os.path.join(d, "air-range.height.asc"), "w", newline="\n") as f:
        f.write(f"ncols {N}\nnrows {N}\nxllcenter {-HALF:.0f}\nyllcenter {-HALF:.0f}\ncellsize {CELL:.0f}\nNODATA_value -9999\n")
        f.write("\n".join(rows) + "\n")
    with open(os.path.join(d, "terrain.json"), "w", newline="\n") as f:
        json.dump({"schemaVersion": 2, "origin": {"lat": 49.0, "lon": 16.0, "alt": 0.0}, "name": "air-range", "world": "air-range.world.geojson"}, f, indent=2)
        f.write("\n")
    world = {"type": "FeatureCollection",
             "hrot": {"schemaVersion": 1, "bounds": [-HALF, -HALF, HALF, HALF], "groundZ": 100, "heightGrid": "air-range.height.asc",
                      "description": "The air-combat range (CE-10001): 2 x 2 km of rolling hills (100 m +- 40), a 200 m ridge along x 500 "
                                     "(south of y 400) and a wall rising 1:1.8 to a 720 m plateau (north of y 600); beyond the edge the ridge and plateau run on. Generated by "
                                     "scripts/gen-air-combat-scenarios.py. Local metres, X east, Y north, Z up."},
             "features": []}
    with open(os.path.join(d, "air-range.world.geojson"), "w", newline="\n") as f:
        json.dump(world, f, indent=1); f.write("\n")


def quat(fwd, up):
    """The System.Numerics quaternion whose rows are fwd, left, up (X forward, Y left, Z up — Steer3D.FromBasis)."""
    n = math.sqrt(sum(a * a for a in fwd)); fwd = [a / n for a in fwd]
    d = sum(a * b for a, b in zip(up, fwd)); up = [a - fwd[i] * d for i, a in enumerate(up)]
    n = math.sqrt(sum(a * a for a in up)); up = [a / n for a in up]
    left = [up[1] * fwd[2] - up[2] * fwd[1], up[2] * fwd[0] - up[0] * fwd[2], up[0] * fwd[1] - up[1] * fwd[0]]
    m11, m12, m13 = fwd; m21, m22, m23 = left; m31, m32, m33 = up
    tr = m11 + m22 + m33
    if tr > 0:
        s = math.sqrt(tr + 1.0) * 2; w = s / 4; x = (m23 - m32) / s; y = (m31 - m13) / s; z = (m12 - m21) / s
    elif m11 >= m22 and m11 >= m33:
        s = math.sqrt(1.0 + m11 - m22 - m33) * 2; w = (m23 - m32) / s; x = s / 4; y = (m12 + m21) / s; z = (m13 + m31) / s
    elif m22 > m33:
        s = math.sqrt(1.0 + m22 - m11 - m33) * 2; w = (m31 - m13) / s; x = (m21 + m12) / s; y = s / 4; z = (m32 + m23) / s
    else:
        s = math.sqrt(1.0 + m33 - m11 - m22) * 2; w = (m12 - m21) / s; x = (m31 + m13) / s; y = (m32 + m23) / s; z = s / 4
    return [round(x, 6), round(y, 6), round(z, 6), round(w, 6)]


def yaw(deg):
    r = math.radians(deg) / 2
    return [0, 0, round(math.sin(r), 6), round(math.cos(r), 6)]


def gid(scn, k):
    return f"ac{scn:06x}-0000-4000-8000-{k:012x}"


def jet(name, tkb, pos, rot, vel, force="Friend", **extra):
    e = {"SimTransform": {"Position": [round(v, 1) for v in pos], "Rotation": rot}, "SimVelocity": {"Linear": [round(v, 2) for v in vel]},
         "TkbIdentity": {"TkbType": tkb}, "EntityInfo": {"Name": name, "ForceId": force}, "Health": {"Current": 400 if tkb == 401 else 450, "Max": 400 if tkb == 401 else 450}}
    e.update(extra)
    return e


def write(name, description, entities, checks):
    d = os.path.join(ROOT, "scenarios", "demos", "air", name)
    os.makedirs(d, exist_ok=True)
    scn = {"$meta": {"docType": "Hrot.Scenario", "schemaVersion": 1},
           "header": {"subsystemType": "Hrot.Scenario", "schemaVersion": "1.0", "terrainName": "air-range", "description": description},
           "entities": entities}
    with open(os.path.join(d, "scenario.json"), "w", newline="\n") as f:
        json.dump(scn, f, indent=2); f.write("\n")
    with open(os.path.join(d, "checks.json"), "w", newline="\n") as f:
        json.dump(checks, f, indent=2); f.write("\n")


def field(who, path, op, value, **kw):
    r = {"on": "field", "who": who, "path": path, "op": op, "value": value}
    r.update(kw)
    return r


def alive(who):
    return {"name": f"{who} is never lost", "never": field(who, "Health.Current", "<=", 0)}


def s1():
    # ── ac-cruise-altitude — a 3-leg route at 300 m over the hills: each leg ONE altitude (AC-1) ──────────────────────────────────────
    wps = [(-4000, -3000), (2500, -3000), (2500, 300), (-4000, 300)]
    route = {"SimTransform": {"Position": [wps[0][0], wps[0][1], 0], "Rotation": [0, 0, 0, 1]}, "TkbIdentity": {"TkbType": 8802},
             "EntityInfo": {"Name": "Viper route", "ForceId": "Friend"},
             "RoutePlan": {"Waypoints": [{"X": x, "Y": y, "Z": 0, "TargetSpeed": 220, "HeightAgl": 300} for x, y in wps], "IsLoop": False}}
    plan = {"PlanData": {"ActiveTaskId": gid(1, 0xa1), "Tasks": [{"TaskId": gid(1, 0xa1), "ExecutingEngine": "", "BehaviorName": "FollowRoute",
            "BehaviorParams": {"routeEntityId": gid(1, 2), "Speed": 220}, "Triggers": []}]}}
    start = (-5500, -3000)
    viper = jet("Viper", 401, (start[0], start[1], ground_beyond(*start) + 300), yaw(0), (220, 0, 0), MissionPlan=plan)
    expect, anchors = [alive("Viper"), {"name": "GCAS never needed on a cruise route", "never": field("Viper", "FighterPilotState.GcasCount", ">", 0)}], {}
    for i in range(3):
        (ax, ay), (bx, by) = wps[i], wps[i + 1]
        top = max(ground_beyond(ax + (bx - ax) * t / 400, ay + (by - ay) * t / 400) for t in range(401)) + 300
        # the middle third of the leg: past the climb into it, before the climb out of it
        m0 = (ax + (bx - ax) * 0.4, ay + (by - ay) * 0.4); m1 = (ax + (bx - ax) * 0.6, ay + (by - ay) * 0.6)
        anchors[f"leg{i + 1}"] = {"on": "near", "who": "Viper", "point": [round(m0[0]), round(m0[1])], "within": 400}
        anchors[f"leg{i + 1}end"] = {"on": "near", "who": "Viper", "point": [round(m1[0]), round(m1[1])], "within": 400}
        for op, val, word in ((">=", round(top - 15), "below"), ("<=", round(top + 15), "above")):
            expect.append({"name": f"leg {i + 1} holds {top:.0f} m (never {word} ±15)", "never": field("Viper", "SimTransform.Position.2", "<" if op == ">=" else ">", val),
                           "after": f"leg{i + 1}", "before": f"leg{i + 1}end"})
    write("ac-cruise-altitude",
          "What: an F-16 ('Viper') flies a 3-leg route at 300 m over the air-range hills (CE-10001, AC-1). Judge: on each leg it holds ONE altitude — the "
          "highest ground under the leg + 300 m (±15), the climb to a higher leg begins before it; GCAS never takes the stick; it is never lost.",
          {gid(1, 1): viper, gid(1, 2): route},
          {"$doc": "DESIGN_Air_Combat §6 S1 — feature (golden). The leg altitudes are computed by scripts/gen-air-combat-scenarios.py from the terrain's own function.",
           "runFor": 120, "golden": {"every": 10}, "anchors": anchors, "expect": expect})

    # ── ac-gcas-ridge — 50 m toward a 200 m ridge; a second in a 30° dive from 2 000 m (AC-4) ──────────────────────────────────────────
    p1 = (-3000.0, 0.0); p1z = ground_beyond(*p1) + 50
    dest = (3000.0, 0.0)
    v1 = jet("Viper Low", 401, (p1[0], p1[1], p1z), yaw(0), (220, 0, 0),
             NavigationIntent={"Mode": "DirectPoint", "IntentId": 1, "FinalDestination": [dest[0], dest[1], round(ground_beyond(*dest) + 50, 1)], "TargetSpeed": 220})
    p2 = (-3000.0, -2500.0); p2z = ground_beyond(*p2) + 2000
    dive = (math.cos(math.radians(30)), 0, -math.sin(math.radians(30)))
    aim = (p2[0] + 2000 / math.tan(math.radians(30)), p2[1])
    v2 = jet("Viper Dive", 401, (p2[0], p2[1], p2z), quat(dive, (0, 0, 1)), tuple(250 * a for a in dive),
             NavigationIntent={"Mode": "AirCombat", "IntentId": 1},
             AirCombatSteer={"Manoeuvre": "PurePursuit", "Point": [round(aim[0]), round(aim[1]), round(ground_beyond(*aim))], "Throttle": 1})
    write("ac-gcas-ridge",
          "What: two F-16s and the ground (CE-10001, AC-4). 'Viper Low' is ordered to a point 50 m over the ground beyond a 200 m ridge (x 500 m); "
          "'Viper Dive' dives at 30° from 2 000 m at a point on the ground, still pressing. Judge: GCAS takes the stick in both (GcasCount ≥ 1); "
          "neither is lost; neither goes below 8 m.",
          {gid(2, 1): v1, gid(2, 2): v2},
          {"$doc": "DESIGN_Air_Combat §6 S1 — feature (golden).", "runFor": 60, "golden": {"every": 10},
           "expect": [{"name": "GCAS saves Viper Low", **field("Viper Low", "FighterPilotState.GcasCount", ">=", 1)},
                      {"name": "GCAS saves Viper Dive", **field("Viper Dive", "FighterPilotState.GcasCount", ">=", 1)},
                      alive("Viper Low"), alive("Viper Dive"),
                      {"name": "Viper Low never below 8 m", **field("Viper Low", "FighterPilotState.MinAgl", ">=", 8), "atEnd": True},
                      {"name": "Viper Dive never below 8 m", **field("Viper Dive", "FighterPilotState.MinAgl", ">=", 8), "atEnd": True}]})

    # ── ac-gcas-inverted — inverted, 60° nose-down at 400 m/s from 3 000 m (AC-4) ───────────────────────────────────────────────────────
    p = (-2000.0, -3000.0); pz = ground_beyond(*p) + 3000
    f = (math.cos(math.radians(60)), 0, -math.sin(math.radians(60)))
    wl = (math.sin(math.radians(60)), 0, math.cos(math.radians(60)))   # the wings-level lift for that nose
    aim = (p[0] + 3000 / math.tan(math.radians(60)), p[1])
    v = jet("Viper", 401, (p[0], p[1], pz), quat(f, tuple(-a for a in wl)), tuple(400 * a for a in f),
            NavigationIntent={"Mode": "AirCombat", "IntentId": 1},
            AirCombatSteer={"Manoeuvre": "PurePursuit", "Point": [round(aim[0]), round(aim[1]), round(ground_beyond(*aim))], "Throttle": 1})
    write("ac-gcas-inverted",
          "What: an F-16 INVERTED, 60° nose-down at 400 m/s from 3 000 m over the hills, its steer still pressing at the ground (CE-10001, AC-4). "
          "Judge: GCAS rolls it upright and pulls it out (GcasCount ≥ 1); it is never lost.",
          {gid(3, 1): v},
          {"$doc": "DESIGN_Air_Combat §6 S1 — feature (golden).", "runFor": 40, "golden": {"every": 5},
           "expect": [{"name": "GCAS takes the stick", **field("Viper", "FighterPilotState.GcasCount", ">=", 1)}, alive("Viper")]})

    # ── ac-gcas-steep-ridge — at 150 m toward a wall it cannot out-climb (AC-4) ──────────────────────────────────────────────────────────
    p = (-500.0, -300.0); pz = grid(*p) + 150
    dest = (-500.0, 2500.0)
    v = jet("Viper", 401, (p[0], p[1], pz), yaw(90), (0, 220, 0),
            NavigationIntent={"Mode": "DirectPoint", "IntentId": 1, "FinalDestination": [dest[0], dest[1], round(ground_beyond(*dest) + 150, 1)], "TargetSpeed": 220})
    write("ac-gcas-steep-ridge",
          "What: an F-16 at 150 m flies north at a wall rising 1:1.8 to a 720 m plateau (north of y 600) — no climb clears it (CE-10001, AC-4). "
          "Judge: GCAS takes the stick and turns away (GcasCount ≥ 1); it is never lost.",
          {gid(4, 1): v},
          {"$doc": "DESIGN_Air_Combat §6 S1 — feature (golden).", "runFor": 60, "golden": {"every": 10},
           "expect": [{"name": "GCAS takes the stick", **field("Viper", "FighterPilotState.GcasCount", ">=", 1)}, alive("Viper")]})

    # ── ac-map-edge — a route that leaves the terrain and comes back (S0 ②) ─────────────────────────────────────────────────────────────
    wps = [(-500, -1500), (6000, -1500), (6000, -2500), (-500, -2500)]
    route = {"SimTransform": {"Position": [wps[0][0], wps[0][1], 0], "Rotation": [0, 0, 0, 1]}, "TkbIdentity": {"TkbType": 8802},
             "EntityInfo": {"Name": "Edge route", "ForceId": "Friend"},
             "RoutePlan": {"Waypoints": [{"X": x, "Y": y, "Z": 0, "TargetSpeed": 220, "HeightAgl": 300} for x, y in wps], "IsLoop": False}}
    plan = {"PlanData": {"ActiveTaskId": gid(5, 0xa1), "Tasks": [{"TaskId": gid(5, 0xa1), "ExecutingEngine": "", "BehaviorName": "FollowRoute",
            "BehaviorParams": {"routeEntityId": gid(5, 2), "Speed": 220}, "Triggers": []}]}}
    start = (-2000.0, -1500.0)
    v = jet("Viper", 401, (start[0], start[1], ground_beyond(*start) + 300), yaw(0), (220, 0, 0), MissionPlan=plan)
    write("ac-map-edge",
          "What: an F-16 flies a route at 300 m that leaves the 2 km air-range grid at x 1 km, turns 5 km beyond its edge and comes back "
          "(CE-10001; S0 ②: beyond the edge the ground is the edge's height + low hills). Judge: GCAS is never needed; it is never lost.",
          {gid(5, 1): v, gid(5, 2): route},
          {"$doc": "DESIGN_Air_Combat §6 S1 — feature (golden).", "runFor": 150, "golden": {"every": 10},
           "anchors": {"beyond": {"on": "near", "who": "Viper", "point": [6000, -2000], "within": 1000}},
           "expect": [{"name": "it flies beyond the edge", "on": "near", "who": "Viper", "point": [6000, -2000], "within": 1000},
                      {"name": "GCAS never needed", "never": field("Viper", "FighterPilotState.GcasCount", ">", 0)}, alive("Viper")]})


if __name__ == "__main__":
    write_terrain()
    s1()
    print("air-range terrain + S1 scenarios written")
