using System;
using System.Collections.Generic;
using Fdp.Core;
using Fdp.Interfaces;
using Fdp.Toolkit.Animals;
using Fdp.Toolkit.Tkb.Domain;

namespace Hrot.Core.Tkb
{
    /// <summary>
    /// ⭐ CE-4623 (animals AU-8; docs/designs/animals/DESIGN_Animals.md AN-19 / AR-7, §6.1; docs/designs/audio/DESIGN_FPS_Audio.md) — the ANIMAL sound types, the twin of <see cref="VoiceTkbCatalog"/>: the block <b>7800–7895</b>,
    /// <c>7800 + species · 8 + line</c> (species = the TKB order 700…711, <see cref="AnimalSpecies"/>; lines 0 call at rest · 1 alarm · 2 the special — bark, squeal, crow · 3 hooves walk · 4 trot · 5 gallop · 6 wings · 7 flutter).
    /// Each a TKB-style entry with its <see cref="SoundDto"/> (a placeholder generated by <c>SoundSynthesizer.Animal</c> until a recording is named), hidden from the palette. Backend registers the TYPES and the closed-form call
    /// timing (AB-8); this is the mixer side: the clips, the ranges, the priorities.
    /// </summary>
    public static class AnimalSoundCatalog
    {
        /// <summary>The first animal sound type (§6.1).</summary>
        public const long Base = 7800;
        public const int Species = 16, Lines = 8, Count = Species * Lines;   // 128: 7800 … 7927 (⭐ CE-4649 part D: species 14 = Rabbit, 15 = HuntingDog) (⭐ CE-4649 part C ④: species 12 = Duck, 13 = DuckFlock — the block grew by two species)
        public const int Call = 0, Alarm = 1, Special = 2, HoovesWalk = 3, HoovesTrot = 4, HoovesGallop = 5, Wings = 6, Flutter = 7;

        /// <summary>The animals' priorities: a call is ambient colour, an alarm or a bark is what the operator must catch (the voices' level), movement sits with footsteps.</summary>
        public const byte PriorityCall = 2, PriorityAlarm = 4, PriorityMoving = 2;

        /// <summary>The sound type of (<paramref name="species"/> 0…11, <paramref name="line"/> 0…7).</summary>
        public static long TypeOf(int species, int line) => Base + species * Lines + line;

        /// <summary>The species (0…11) of a sound type in the block; −1 when it is none.</summary>
        public static int SpeciesOf(long type) => type >= Base && type < Base + Count ? (int)((type - Base) / Lines) : -1;

        /// <summary>The line (0…7) of a sound type in the block.</summary>
        public static int LineOf(long type) => (int)((type - Base) % Lines);

        /// <summary>The species of an animal TKB type 700…711 (its sound block's <c>s</c>); −1 for any other type.</summary>
        public static int SpeciesOfEntityType(long tkbType) => tkbType >= 700 && tkbType <= 711 ? (int)(tkbType - 700) : tkbType >= 713 && tkbType <= 716 ? (int)(tkbType - 701) : -1;   // 712 is the area: no voice

        /// <summary>Every type of the block, with its (species, line).</summary>
        public static IEnumerable<(long Type, int Species, int Line)> All()
        {
            for (int s = 0; s < Species; s++) for (int l = 0; l < Lines; l++) yield return (TypeOf(s, l), s, l);
        }

        /// <summary>How far a species' rest call carries (m): the loud animals far, a cat hardly.</summary>
        public static float CallRange(int species) => species switch
        {
            0 => 200f, 1 => 150f, 2 => 250f, 3 => 250f, 4 => 250f, 5 => 200f, 6 => 50f, 7 => 120f, 8 => 80f, 9 => 80f, 10 => 150f, 12 => 200f, 13 => 200f, 14 => 30f, 15 => 200f, _ => 150f,
        };

        /// <summary>The sound of a type of the block — its TKB <see cref="SoundDto"/> when one is registered, else the built-in placeholder; null for a type that is no animal sound.</summary>
        public static SoundDto? SoundOf(ITkbDatabase? tkb, long type)
        {
            int s = SpeciesOf(type);
            if (s < 0) return null;
            if (tkb != null && tkb.TryGetByType(type, out var t) && t?.GetDescriptor<SoundDto>() is { } own) return own;
            return Placeholders[(int)(type - Base)];
        }

        private static readonly SoundDto[] Placeholders = BuildPlaceholders();

        private static SoundDto[] BuildPlaceholders()
        {
            var all = new SoundDto[Count];
            for (int s = 0; s < Species; s++)
                for (int l = 0; l < Lines; l++)
                {
                    float call = CallRange(s);
                    all[s * Lines + l] = l switch
                    {
                        Call => New(call * 0.5f, call, -8f, PriorityCall, false, 6f),
                        Alarm => New(call * 0.75f, call * 1.5f, -4f, PriorityAlarm, false, 6f),
                        Special => New(call * 0.75f, call * (s == 5 || s == 15 ? 1.75f : 1.5f), -3f, PriorityAlarm, false, 6f),   // a bark carries
                        HoovesWalk => New(8f, 45f, -22f, PriorityMoving, true, 0f),
                        HoovesTrot => New(10f, 60f, -19f, PriorityMoving, true, 0f),
                        HoovesGallop => New(14f, 90f, -15f, PriorityMoving, true, 0f),
                        Wings => New(10f, 100f, -16f, PriorityMoving, true, 0f),
                        _ => New(6f, 40f, -12f, PriorityMoving, false, 0f),
                    };
                }
            return all;
        }

        private static SoundDto New(float reference, float range, float db, byte priority, bool loop, float jitterPct)
            => new() { Synth = SoundSynth.Animal, ReferenceM = reference, RangeM = range, Category = SoundCategory.Ambient, Priority = priority, VolumeDb = db, Loop = loop, PitchJitter = jitterPct / 100f };

        // ── the closed-form call timing (the operator's side; backend's AB-8 gives the AI the same rule) ────────────────────────────────────────────────────────────

        /// <summary>The seconds between one species' rest calls — a range, a herd is not a choir.</summary>
        public static (float Min, float Max) Interval(int species) => species switch
        {
            0 => (14f, 40f), 1 => (8f, 25f), 2 => (20f, 60f), 3 => (20f, 60f), 4 => (20f, 60f), 5 => (10f, 40f), 6 => (25f, 70f), 7 => (5f, 15f), 8 => (4f, 12f), 9 => (3f, 10f), 10 => (10f, 30f), 12 => (5f, 14f), 13 => (4f, 10f), 14 => (40f, 120f), 15 => (10f, 40f), _ => (10f, 30f),
        };

        private static uint Hash(uint x) { x ^= x >> 16; x *= 0x7feb352du; x ^= x >> 15; x *= 0x846ca68bu; x ^= x >> 16; return x; }

        /// <summary>
        /// ⭐ The rest calls this animal has made by sim time <paramref name="simTime"/>: <c>floor(t / period + phase)</c> with its period and phase from (<paramref name="key"/> — the stable key,
        /// <paramref name="seed"/>) — a pure function, so the operator and the AI agree, and a seek or a late join hears the same calls. A call is HEARD when this number goes up.
        /// </summary>
        public static long CallsMade(int species, uint key, uint seed, double simTime)
        {
            var (min, max) = Interval(species);
            uint h = Hash(key * 0x9E3779B1u ^ seed);
            float period = min + (max - min) * ((h & 0xFFFF) / 65536f);
            float phase = ((h >> 16) & 0xFFFF) / 65536f;
            return (long)Math.Floor(simTime / period + phase);
        }

        /// <summary>The hooves' line for a speed (m/s) in a species' bands: walk / trot / gallop (a canter sounds as a gallop's lighter beat).</summary>
        public static int HoovesLine(float speed, float walkMax, float trotMax) => speed <= walkMax ? HoovesWalk : speed <= trotMax ? HoovesTrot : HoovesGallop;
    }
}
