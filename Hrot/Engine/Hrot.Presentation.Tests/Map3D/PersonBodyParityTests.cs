namespace Hrot.Presentation.Tests.Map3D;

/// <summary>
/// ⭐⭐ <c>CE-3209</c> (backend, cross-lane rail in ui's suite; docs/designs/hit-location/DESIGN_Body_Parts_And_Hit_Location.md HL-1) — the
/// boxes the rounds meet (<see cref="PersonBody"/>, Fdp.Toolkits) are the boxes the block figure draws (<see cref="BlockFigure"/>), pose by
/// pose and part by part. ⭐ The sim's table is GENERATED from the figure: <c>HROT_GEN_PERSON_BODY=1 dotnet test --filter PersonBodyParity</c>
/// rewrites <c>PersonBody.Tables.g.cs</c>. 🔴 Change the figure without regenerating and this rail fails — a round would no longer land
/// where the part is drawn. ⏭ S1c: the figure reads its geometry from <see cref="PersonBody"/> and this rail becomes trivially true.
/// </summary>
public class PersonBodyParityTests
{
    /// <summary>The figure's authoring size (<c>BlockFigure.S</c>): its parts are fractions of it, so this gives back the metres.</summary>
    private static readonly Vector3 FigureSize = new(0.35f, 0.55f, 1.8f);

    /// <summary>The drawn parts of each <see cref="PersonPose"/>, in its order.</summary>
    private static KitPart[] DrawnParts(PersonPose pose) => pose switch
    {
        PersonPose.StandingAtEase => BlockFigure.Parts(StanceId.Standing, true, WeaponPostureKind.AtEase),
        PersonPose.StandingReady => BlockFigure.Parts(StanceId.Standing, true, WeaponPostureKind.Ready),
        PersonPose.StandingAimed => BlockFigure.Parts(StanceId.Standing, true, WeaponPostureKind.Aimed),
        PersonPose.CrouchedAtEase => BlockFigure.Parts(StanceId.Crouched, true, WeaponPostureKind.AtEase),
        PersonPose.CrouchedReady => BlockFigure.Parts(StanceId.Crouched, true, WeaponPostureKind.Ready),
        PersonPose.CrouchedAimed => BlockFigure.Parts(StanceId.Crouched, true, WeaponPostureKind.Aimed),
        PersonPose.Prone => BlockFigure.Parts(StanceId.Prone, true, WeaponPostureKind.AtEase),
        PersonPose.CivilianStanding => BlockFigure.Parts(StanceId.Standing, false),
        PersonPose.CivilianCrouched => BlockFigure.Parts(StanceId.Crouched, false),
        PersonPose.CivilianProne => BlockFigure.Parts(StanceId.Prone, false),
        PersonPose.Downed => BlockFigure.Dead(false),
        _ => throw new ArgumentOutOfRangeException(nameof(pose)),
    };

    /// <summary>The body box a drawn part is: the figure's own transform, taken apart into centre, half-size and rotation.</summary>
    private static BodyBox BoxOf(KitPart part, byte id)
    {
        Assert.Equal(PartShape.Box, part.Shape);
        Assert.True(Matrix4x4.Decompose(part.BodyTransform(FigureSize), out var scale, out var rotation, out var centre));
        return new BodyBox(id, centre, scale * 0.5f, Quaternion.Normalize(rotation));
    }

    [Fact]
    public void CE3209_TheBoxesTheRoundsMeet_AreTheBoxesTheFigureDraws()
    {
        var poses = Enum.GetValues<PersonPose>();
        if (Environment.GetEnvironmentVariable("HROT_GEN_PERSON_BODY") == "1") Generate(poses);
        Assert.Equal(PersonPart.Count, BlockFigure.HeadIndex + 5);   // ten body parts before the weapon, head at 5
        foreach (var pose in poses)
        {
            var drawn = DrawnParts(pose);
            var sim = PersonBody.Boxes(pose);
            Assert.True(sim.Length == PersonPart.Count, $"{pose}: the sim has {sim.Length} boxes — regenerate (HROT_GEN_PERSON_BODY=1)");
            for (int i = 0; i < PersonPart.Count; i++)
            {
                var want = BoxOf(drawn[i], (byte)i);
                var got = sim[i];
                Assert.Equal(want.Part, got.Part);
                Assert.True(Vector3.Distance(want.Centre, got.Centre) < 1e-3f, $"{pose} part {PersonPart.NameOf((byte)i)}: centre {got.Centre} vs drawn {want.Centre}");
                Assert.True(Vector3.Distance(want.Half, got.Half) < 1e-3f, $"{pose} part {PersonPart.NameOf((byte)i)}: size {got.Half} vs drawn {want.Half}");
                Assert.True(MathF.Abs(Quaternion.Dot(want.Rotation, got.Rotation)) > 0.9999f, $"{pose} part {PersonPart.NameOf((byte)i)}: rotation differs");
            }
        }
        // a sanity of the figure's size: a standing man's head reaches about 1.8 m
        var head = PersonBody.Boxes(PersonPose.StandingAtEase)[PersonPart.Head];
        Assert.InRange(head.Centre.Z + head.Half.Z, 1.6f, 1.9f);
    }

    private static void Generate(PersonPose[] poses)
    {
        static string F(float v) => v.ToString("0.#####", CultureInfo.InvariantCulture) + "f";
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated> by Hrot.Presentation.Tests PersonBodyParityTests (HROT_GEN_PERSON_BODY=1) from the drawn BlockFigure —");
        sb.AppendLine("//   do not edit by hand; CE-3209, docs/designs/hit-location/DESIGN_Body_Parts_And_Hit_Location.md HL-1 </auto-generated>");
        sb.AppendLine("using System.Numerics;");
        sb.AppendLine();
        sb.AppendLine("namespace Fdp.Toolkit.Physics.BodyParts");
        sb.AppendLine("{");
        sb.AppendLine("    public static partial class PersonBody");
        sb.AppendLine("    {");
        sb.AppendLine($"        private static readonly BodyBox[][] Tables = new BodyBox[{poses.Length}][]");
        sb.AppendLine("        {");
        foreach (var pose in poses)
        {
            sb.AppendLine($"            new BodyBox[] // {pose}");
            sb.AppendLine("            {");
            var drawn = DrawnParts(pose);
            for (int i = 0; i < PersonPart.Count; i++)
            {
                var b = BoxOf(drawn[i], (byte)i);
                sb.AppendLine($"                new({i}, new({F(b.Centre.X)}, {F(b.Centre.Y)}, {F(b.Centre.Z)}), new({F(b.Half.X)}, {F(b.Half.Y)}, {F(b.Half.Z)}), " +
                              $"new({F(b.Rotation.X)}, {F(b.Rotation.Y)}, {F(b.Rotation.Z)}, {F(b.Rotation.W)})),   // {PersonPart.NameOf((byte)i)}");
            }
            sb.AppendLine("            },");
        }
        sb.AppendLine("        };");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        var dir = TestRepo.Root;
        File.WriteAllText(Path.Combine(dir!, "FDP", "Toolkits", "Fdp.Toolkits", "Physics", "BodyParts", "PersonBody.Tables.g.cs"), sb.ToString());
    }
}
