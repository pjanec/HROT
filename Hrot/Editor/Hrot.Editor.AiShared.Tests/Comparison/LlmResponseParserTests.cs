using Hrot.Editor.AiShared.Comparison;

namespace Hrot.Editor.AiShared.Tests.Comparison;

public sealed class LlmResponseParserTests
{
    private const string WellFormedText =
        "----- HUMAN SUMMARY -----\n" +
        "The combat behavior in OrcGuard_BT has been refined to be more aggressive\n" +
        "about firing. The previously-single-shot Action node now repeats up to 3\n" +
        "times via a new Repeater decorator, which means the guard will commit to a\n" +
        "burst before re-evaluating threats.\n" +
        "\n" +
        "No other behavior changes were detected. Threat detection logic is unchanged.\n" +
        "\n" +
        "----- STRUCTURED CHANGES (JSON) -----\n" +
        "{\n" +
        "  \"summary\": \"Burst-fire behavior added to OrcGuard combat; ammo tracking variable renamed.\",\n" +
        "  \"changes\": [\n" +
        "    {\n" +
        "      \"kind\": \"node_added\",\n" +
        "      \"elementId\": \"b4711d22-1d22-4c5e-9a3b-2c4d5e6f7a8b\",\n" +
        "      \"elementDescription\": \"Repeater decorator wrapping AimAndFire\",\n" +
        "      \"field\": null,\n" +
        "      \"oldValue\": null,\n" +
        "      \"newValue\": \"Repeater(count: 3)\",\n" +
        "      \"severity\": \"behavior\",\n" +
        "      \"description\": \"AimAndFire now repeats 3 times per Sequence iteration.\"\n" +
        "    },\n" +
        "    {\n" +
        "      \"kind\": \"variable_renamed\",\n" +
        "      \"elementId\": \"BurstShotsRemaining\",\n" +
        "      \"elementDescription\": \"AmmoCount blackboard variable\",\n" +
        "      \"field\": \"name\",\n" +
        "      \"oldValue\": \"AmmoCount\",\n" +
        "      \"newValue\": \"BurstShotsRemaining\",\n" +
        "      \"severity\": \"cosmetic\",\n" +
        "      \"description\": \"Variable renamed for clarity.\"\n" +
        "    }\n" +
        "  ]\n" +
        "}";

    [Fact]
    public void Parse_WellFormedResponse_ParsesAllFieldsAndZeroWarnings()
    {
        var result = LlmResponseParser.Parse(WellFormedText);

        Assert.Equal(2, result.Changes.Count);
        Assert.Empty(result.Warnings);
        Assert.NotNull(result.HumanSummary);
        Assert.Contains("OrcGuard_BT", result.HumanSummary);

        var first = result.Changes[0];
        Assert.Equal("node_added", first.Kind);
        Assert.Equal("b4711d22-1d22-4c5e-9a3b-2c4d5e6f7a8b", first.ElementId);
        Assert.Equal("behavior", first.Severity);

        var second = result.Changes[1];
        Assert.Equal("variable_renamed", second.Kind);
        Assert.Equal("BurstShotsRemaining", second.ElementId);
        Assert.Equal("cosmetic", second.Severity);
    }

