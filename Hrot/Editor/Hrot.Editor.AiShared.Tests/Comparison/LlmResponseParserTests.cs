            "{\n" +
            "  \"summary\": \"Burst-fire behavior added to OrcGuard combat; ammo tracking variable renamed.\",\n" +
            "  \"changes\": [\n" +
            "    {\n" +
            "      \"kind\": \"node_added\",\n" +
            "      \"elementId\": \"b4711d22-1d22-4c5e-9a3b-2c4d5e6f7a8b\",\n" +
            "      \"elementDescription\": \"Repeater decorator wrapping AimAndFire\",\n" +
            "      \"field\": null,\n" +
            "      \"oldValue\": null,\n" +
            "      \"newValue\": \"Repeater(count: 3)\",\n" +
            "      \"severity\": \"behavior\",\n" +
            "      \"description\": \"AimAndFire now repeats 3 times.\"\n" +
            "    },\n" +
            "    {\n" +
            "      \"kind\": \"variable_renamed\",\n" +
            "      \"elementId\": \"BurstShotsRemaining\",\n" +
            "      \"elementDescription\": \"AmmoCount blackboard variable\",\n" +
            "      \"field\": \"name\",\n" +
            "      \"oldValue\": \"AmmoCount\",\n" +
            "      \"newValue\": \"BurstShotsRemaining\",\n" +
            "      \"severity\": \"cosmetic\",\n" +
            "      \"description\": \"Variable renamed for clarity.\"\n" +
            "    }\n" +
