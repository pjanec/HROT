    [Fact]
    public void Parse_NullElementId_ParsedNormallyNoWarning()
    {
        const string text =
            "----- HUMAN SUMMARY -----\nSummary.\n" +
            "----- STRUCTURED CHANGES (JSON) -----\n" +
            "{\n" +
            "  \"summary\": \"Test.\",\n" +
            "  \"changes\": [\n" +
            "    {\n" +
            "      \"kind\": \"intent_shift\",\n" +
            "      \"elementId\": null,\n" +
            "      \"elementDescription\": \"Entire subgraph\",\n" +
            "      \"field\": null,\n" +
            "      \"oldValue\": null,\n" +
            "      \"newValue\": null,\n" +
            "      \"severity\": \"behavior\",\n" +
            "      \"description\": \"Overall behavior shifted.\"\n" +
