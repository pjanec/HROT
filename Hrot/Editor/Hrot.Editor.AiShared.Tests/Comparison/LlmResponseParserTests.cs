    [Fact]
    public void Parse_ExtraLeadingProseBeforeHumanMarker_HumanSummaryCorrectlyExtracted()
    {
        var text =
            "This is a comparison of two BTree assets.\n" +
            "The assets were generated by the Hrot AI editor.\n" +
            "Analysis follows below.\n" +
            WellFormedText;

        var result = LlmResponseParser.Parse(text);

        Assert.Equal(2, result.Changes.Count);
        Assert.Empty(result.Warnings);
        // Human summary should NOT include the extra prose
        Assert.NotNull(result.HumanSummary);
        Assert.DoesNotContain("generated by the Hrot AI editor", result.HumanSummary!);
    }

    [Fact]
    public void Parse_MarkerAbsent_FallbackFirstBraceToLastBrace()
    {
        // No markers -- just raw JSON with some prose before the first {.
        const string text =
            "Here is the analysis:\n" +
            "{\n" +
            "  \"summary\": \"Some change.\",\n" +
            "  \"changes\": [\n" +
            "    {\n" +
            "      \"kind\": \"node_added\",\n" +
            "      \"elementId\": \"abc\",\n" +
            "      \"elementDescription\": \"Some node\",\n" +
            "      \"field\": null,\n" +
            "      \"oldValue\": null,\n" +
            "      \"newValue\": null,\n" +
            "      \"severity\": \"feature\",\n" +
            "      \"description\": \"A new node was added.\"\n" +
            "    }\n" +
            "  ]\n" +
            "}";

        var result = LlmResponseParser.Parse(text);

        Assert.Single(result.Changes);
        Assert.Empty(result.Warnings);
        Assert.Equal("node_added", result.Changes[0].Kind);
    }

    [Fact]
    public void Parse_TruncatedRecoverable_Returns1ChangeAnd1Warning()
    {
        // Well-formed JSON with only first change present; closing ] and } missing.
        const string text =
            "----- HUMAN SUMMARY -----\n" +
            "Summary text.\n" +
            "\n" +
            "----- STRUCTURED CHANGES (JSON) -----\n" +
            "{\n" +
            "  \"summary\": \"Burst-fire behavior added.\",\n" +
            "  \"changes\": [\n" +
            "    {\n" +
            "      \"kind\": \"node_added\",\n" +
            "      \"elementId\": \"b4711d22-1d22-4c5e-9a3b-2c4d5e6f7a8b\",\n" +
            "      \"elementDescription\": \"Repeater decorator wrapping AimAndFire\",\n" +
            "      \"field\": null,\n" +
            "      \"oldValue\": null,\n" +
            "      \"newValue\": \"Repeater(count: 3)\",\n" +
            "      \"severity\": \"behavior\",\n" +
            "      \"description\": \"AimAndFire now repeats 3 times.\"\n" +
            "    }";
        // No closing ] or }

        var result = LlmResponseParser.Parse(text);

        Assert.Single(result.Changes);
        Assert.Single(result.Warnings);
        Assert.Contains("truncated", result.Warnings[0], StringComparison.OrdinalIgnoreCase);
    }

    [Fact]
    public void Parse_TruncatedUnrecoverable_Returns0ChangesAnd1Warning()
    {
        // JSON cut mid-key, no complete } to recover from.
        const string text = "{ \"summary\": \"abc\", \"changes\": [{ \"kind\":";

        var result = LlmResponseParser.Parse(text);

        Assert.Empty(result.Changes);
        Assert.Single(result.Warnings);
        Assert.Contains("truncated", result.Warnings[0], StringComparison.OrdinalIgnoreCase);
    }

