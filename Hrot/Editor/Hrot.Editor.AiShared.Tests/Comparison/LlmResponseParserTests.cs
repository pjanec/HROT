    [Fact]
    public void Parse_EmptyChangesArray_ReturnsEmptyChangesNoWarnings()
    {
        const string text =
            "----- HUMAN SUMMARY -----\nNo changes detected.\n" +
            "----- STRUCTURED CHANGES (JSON) -----\n" +
            "{\n" +
            "  \"summary\": \"No changes.\",\n" +
            "  \"changes\": []\n" +
            "}";

        var result = LlmResponseParser.Parse(text);

        Assert.Empty(result.Changes);
        Assert.Empty(result.Warnings);
        Assert.Equal("No changes.", result.TopLevelSummary);
    }

